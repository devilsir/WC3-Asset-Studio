function parseTable(raw){
  const map=new Map();
  for(const line of String(raw||'').split(/\r?\n/)){
    const m=/^\s*([^\s]{4})\s+(.+?)\s*$/.exec(line);
    if(!m)continue;
    map.set(m[1].toUpperCase(),m[2]);
  }
  return map;
}
const spawn=parseTable(SPAWN_RAW),splat=parseTable(SPLAT_RAW),ubersplat=parseTable(UBERSPLAT_RAW),sound=parseTable(SOUND_RAW);
const TYPE_INFO=Object.freeze({
  SPN:{kind:'spawn',label:'Spawn Object',table:spawn},
  SPL:{kind:'splat',label:'Blood Splat',table:splat},
  UBR:{kind:'ubersplat',label:'Uber Splat',table:ubersplat},
  FPT:{kind:'footprint',label:'Footprint',table:splat},
  SND:{kind:'sound',label:'Sound',table:sound}
});
function resolve(name){
  const raw=String(name||'').trim();
  const m=/^(SPN|SPL|UBR|FPT|SND)(.)([A-Za-z0-9]{4})/i.exec(raw);
  if(!m)return{valid:false,name:raw,typeCode:'',slot:'',id:'',kind:'unknown',label:'Unknown Event Object',value:'',path:''};
  const typeCode=m[1].toUpperCase(),slot=m[2],id=m[3].toUpperCase(),info=TYPE_INFO[typeCode],value=info?.table?.get(id)||'';
  return{
    valid:true,name:raw,typeCode,slot,id,kind:info.kind,label:info.label,value,
    path:info.kind==='spawn'?value:'',display:value||id,
    key:`${typeCode}${slot}${id}`
  };
}
const api={
  resolve,
  tables:{spawn,splat,ubersplat,sound},
  counts:{spawn:spawn.size,splat:splat.size,ubersplat:ubersplat.size,sound:sound.size},
  source:'War3ModelEditor/Data compatibility tables'
};
window.WC3_EVENT_OBJECT_DATA=api;
